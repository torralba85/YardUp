import { join } from "path";
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import {
  parseDemoReceiptToken,
  verifyAppleSignedTransaction,
  verifyGooglePlayPurchase,
} from "./store-receipt-verifiers";

const BUNDLE_ID = "com.lotfoundry.app";
const PRODUCT_ID = "com.lotfoundry.certificate.credit1";

function b64url(data: Buffer | string): string {
  return Buffer.from(data).toString("base64url");
}

afterEach(() => {
  vi.unstubAllEnvs();
});

describe("parseDemoReceiptToken", () => {
  it("accepts demo: tokens in test env", () => {
    expect(parseDemoReceiptToken("demo:tx-1")).toBe("tx-1");
  });
});

describe("verifyAppleSignedTransaction", () => {
  it("accepts demo tokens without requiring a real JWS", () => {
    const result = verifyAppleSignedTransaction({
      productId: PRODUCT_ID,
      token: "demo:abc",
      bundleId: BUNDLE_ID,
    });
    expect(result).toEqual({
      transactionId: `apple:abc:${PRODUCT_ID}`,
    });
  });

  it("rejects malformed JWS when not a demo token", () => {
    const result = verifyAppleSignedTransaction({
      productId: PRODUCT_ID,
      token: "not.a.valid.jws.payload",
      bundleId: BUNDLE_ID,
    });
    expect(result).toEqual(expect.objectContaining({ error: expect.any(String) }));
    if ("error" in result) {
      expect(result.error).toMatch(/JWS|decoded|certificate|signature/i);
    }
  });

  it("fails closed when no Apple root pin is configured", () => {
    vi.stubEnv("APPLE_ROOT_CA_FINGERPRINT256", "");
    const header = b64url(JSON.stringify({ alg: "ES256", x5c: ["AAAA"] }));
    const payload = b64url(
      JSON.stringify({ bundleId: BUNDLE_ID, productId: PRODUCT_ID, transactionId: "t1" }),
    );
    const result = verifyAppleSignedTransaction({
      productId: PRODUCT_ID,
      token: `${header}.${payload}.AAAA`,
      bundleId: BUNDLE_ID,
    });
    expect(result).toEqual(
      expect.objectContaining({ error: expect.stringMatching(/APPLE_ROOT_CA_FINGERPRINT256/) }),
    );
  });
});

const hasOpenssl = (() => {
  try {
    execFileSync("openssl", ["version"], { stdio: "ignore" });
    return true;
  } catch {
    if (process.platform === "win32") {
      const gitUsrBin = "C:\\Program Files\\Git\\usr\\bin";
      if (existsSync(join(gitUsrBin, "openssl.exe"))) {
        process.env.PATH = `${gitUsrBin};${process.env.PATH || ""}`;
        return true;
      }
    }
    return false;
  }
})();

/** Full-chain tests with a throwaway self-signed cert generated by openssl. */
describe.skipIf(!hasOpenssl)("verifyAppleSignedTransaction pinned chain", () => {
  let dir: string;
  let certDerB64: string;
  let fingerprint256: string;
  let signJws: (
    payload: Record<string, unknown>,
    keyPem?: string,
    certChain?: string[],
  ) => string;
  let keyPem: string;
  let otherKeyPem: string;

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), "lf-store-receipt-"));
    execFileSync("openssl", [
      "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", join(dir, "key.pem"),
    ]);
    execFileSync("openssl", [
      "req", "-new", "-x509",
      "-key", join(dir, "key.pem"),
      "-out", join(dir, "cert.pem"),
      "-days", "2",
      "-subj", "/CN=LotFoundry Receipt Test",
      "-sha256",
    ]);
    execFileSync("openssl", [
      "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", join(dir, "other-key.pem"),
    ]);

    keyPem = readFileSync(join(dir, "key.pem"), "utf8");
    otherKeyPem = readFileSync(join(dir, "other-key.pem"), "utf8");
    const cert = new X509Certificate(readFileSync(join(dir, "cert.pem")));
    certDerB64 = cert.raw.toString("base64");
    fingerprint256 = cert.fingerprint256;

    signJws = (payload, pem = keyPem, certChain = [certDerB64]) => {
      const header = b64url(JSON.stringify({ alg: "ES256", x5c: certChain }));
      const body = b64url(JSON.stringify(payload));
      const signingInput = `${header}.${body}`;
      const signature = sign("sha256", Buffer.from(signingInput), {
        key: createPrivateKey(pem),
        dsaEncoding: "ieee-p1363",
      });
      return `${signingInput}.${signature.toString("base64url")}`;
    };
  });

  afterAll(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  it("verifies a correctly pinned isolated test certificate", () => {
    vi.stubEnv("APPLE_ROOT_CA_FINGERPRINT256", fingerprint256);
    const token = signJws({
      bundleId: BUNDLE_ID,
      productId: PRODUCT_ID,
      transactionId: "tx-pinned-1",
    });
    expect(
      verifyAppleSignedTransaction({ productId: PRODUCT_ID, token, bundleId: BUNDLE_ID }),
    ).toEqual({ transactionId: "tx-pinned-1" });
  });

  it("rejects a multi-certificate chain without StoreKit policy OIDs", () => {
    vi.stubEnv("APPLE_ROOT_CA_FINGERPRINT256", fingerprint256);
    const token = signJws(
      {
        bundleId: BUNDLE_ID,
        productId: PRODUCT_ID,
        transactionId: "tx-wrong-purpose",
      },
      keyPem,
      [certDerB64, certDerB64],
    );
    expect(
      verifyAppleSignedTransaction({ productId: PRODUCT_ID, token, bundleId: BUNDLE_ID }),
    ).toEqual(expect.objectContaining({ error: expect.stringMatching(/StoreKit/i) }));
  });

  it("rejects a chain that is not anchored to the pinned root", () => {
    vi.stubEnv(
      "APPLE_ROOT_CA_FINGERPRINT256",
      "00:11:22:33:44:55:66:77:88:99:AA:BB:CC:DD:EE:FF:00:11:22:33:44:55:66:77:88:99:AA:BB:CC:DD:EE:FF",
    );
    const token = signJws({
      bundleId: BUNDLE_ID,
      productId: PRODUCT_ID,
      transactionId: "tx-forged-1",
    });
    expect(
      verifyAppleSignedTransaction({ productId: PRODUCT_ID, token, bundleId: BUNDLE_ID }),
    ).toEqual(expect.objectContaining({ error: expect.stringMatching(/not anchored/i) }));
  });

  it("rejects a signature made with a key that does not match the chain", () => {
    vi.stubEnv("APPLE_ROOT_CA_FINGERPRINT256", fingerprint256);
    const token = signJws(
      { bundleId: BUNDLE_ID, productId: PRODUCT_ID, transactionId: "tx-wrong-key" },
      otherKeyPem,
    );
    expect(
      verifyAppleSignedTransaction({ productId: PRODUCT_ID, token, bundleId: BUNDLE_ID }),
    ).toEqual(expect.objectContaining({ error: expect.stringMatching(/signature is invalid/i) }));
  });

  it("rejects a valid signature carrying the wrong bundle id", () => {
    vi.stubEnv("APPLE_ROOT_CA_FINGERPRINT256", fingerprint256);
    const token = signJws({
      bundleId: "com.attacker.app",
      productId: PRODUCT_ID,
      transactionId: "tx-wrong-bundle",
    });
    expect(
      verifyAppleSignedTransaction({ productId: PRODUCT_ID, token, bundleId: BUNDLE_ID }),
    ).toEqual(expect.objectContaining({ error: expect.stringMatching(/bundle id/i) }));
  });
});

describe("verifyGooglePlayPurchase", () => {
  it("accepts demo tokens without contacting Google Play API", async () => {
    const result = await verifyGooglePlayPurchase({
      productId: PRODUCT_ID,
      token: "demo:google-tx-1",
      packageName: "com.lotfoundry.app",
      serviceAccountJson: "{}",
    });
    expect(result).toEqual({ transactionId: `google:google-tx-1:${PRODUCT_ID}` });
  });

  it("rejects malformed service account JSON", async () => {
    const result = await verifyGooglePlayPurchase({
      productId: PRODUCT_ID,
      token: "token-non-demo",
      packageName: "com.lotfoundry.app",
      serviceAccountJson: "{not json",
    });
    expect(result).toEqual({ error: "Google Play service account JSON is invalid." });
  });

  it("rejects service account missing client_email or private_key", async () => {
    const result = await verifyGooglePlayPurchase({
      productId: PRODUCT_ID,
      token: "token-non-demo",
      packageName: "com.lotfoundry.app",
      serviceAccountJson: JSON.stringify({ client_email: "test@example.com" }),
    });
    expect(result).toEqual({ error: "Google Play service account is misconfigured." });
  });

  it("handles OAuth authentication failure", async () => {
    const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    const pem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
    const serviceAccountJson = JSON.stringify({
      client_email: "test@example.iam.gserviceaccount.com",
      private_key: pem,
    });

    const mockFetch = vi.fn(async () => new Response("Unauthorized", { status: 401 }));

    const result = await verifyGooglePlayPurchase(
      {
        productId: PRODUCT_ID,
        token: "token-non-demo",
        packageName: "com.lotfoundry.app",
        serviceAccountJson,
      },
      mockFetch as unknown as typeof fetch,
    );

    expect(result).toEqual({ error: "Google Play authentication failed." });
  });

  it("verifies a valid purchased token via the Android Publisher API", async () => {
    const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    const pem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
    const serviceAccountJson = JSON.stringify({
      client_email: "test@example.iam.gserviceaccount.com",
      private_key: pem,
    });

    const mockFetch = vi.fn(async (url: string | URL | Request) => {
      const urlStr = String(url);
      if (urlStr.includes("oauth2.googleapis.com")) {
        return new Response(JSON.stringify({ access_token: "mock-access-token" }), {
          status: 200,
          headers: { "Content-Type": "application/json" },
        });
      }
      if (urlStr.includes("androidpublisher.googleapis.com")) {
        return new Response(
          JSON.stringify({
            purchaseState: 0,
            orderId: "GPA.1234-5678-9012",
            purchaseToken: "valid-play-token",
          }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        );
      }
      return new Response("Not Found", { status: 404 });
    });

    const result = await verifyGooglePlayPurchase(
      {
        productId: PRODUCT_ID,
        token: "valid-play-token",
        packageName: "com.lotfoundry.app",
        serviceAccountJson,
      },
      mockFetch as unknown as typeof fetch,
    );

    expect(result).toEqual({ transactionId: "GPA.1234-5678-9012" });
  });

  it("rejects purchases that are not in a purchased state", async () => {
    const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    const pem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
    const serviceAccountJson = JSON.stringify({
      client_email: "test@example.iam.gserviceaccount.com",
      private_key: pem,
    });

    const mockFetch = vi.fn(async (url: string | URL | Request) => {
      const urlStr = String(url);
      if (urlStr.includes("oauth2.googleapis.com")) {
        return new Response(JSON.stringify({ access_token: "mock-access-token" }), {
          status: 200,
          headers: { "Content-Type": "application/json" },
        });
      }
      if (urlStr.includes("androidpublisher.googleapis.com")) {
        return new Response(
          JSON.stringify({
            purchaseState: 1,
            orderId: "GPA.1234-canceled",
          }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        );
      }
      return new Response("Not Found", { status: 404 });
    });

    const result = await verifyGooglePlayPurchase(
      {
        productId: PRODUCT_ID,
        token: "canceled-play-token",
        packageName: "com.lotfoundry.app",
        serviceAccountJson,
      },
      mockFetch as unknown as typeof fetch,
    );

    expect(result).toEqual({ error: "Google Play purchase is not in a purchased state." });
  });

  it("handles Android Publisher API error responses", async () => {
    const { privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    const pem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
    const serviceAccountJson = JSON.stringify({
      client_email: "test@example.iam.gserviceaccount.com",
      private_key: pem,
    });

    const mockFetch = vi.fn(async (url: string | URL | Request) => {
      const urlStr = String(url);
      if (urlStr.includes("oauth2.googleapis.com")) {
        return new Response(JSON.stringify({ access_token: "mock-access-token" }), {
          status: 200,
          headers: { "Content-Type": "application/json" },
        });
      }
      return new Response("Purchase token not found", { status: 404 });
    });

    const result = await verifyGooglePlayPurchase(
      {
        productId: PRODUCT_ID,
        token: "invalid-token",
        packageName: "com.lotfoundry.app",
        serviceAccountJson,
      },
      mockFetch as unknown as typeof fetch,
    );

    expect(result).toEqual({ error: "Google Play purchase verification failed." });
  });
});

