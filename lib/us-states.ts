export function normalizeStateCode(value: string): string {
  const state = value.trim().toUpperCase();
  if (Object.hasOwn(US_STATE_NAMES, state)) return state;
  return Object.entries(US_STATE_NAMES).find(([, name]) => name.toUpperCase() === state)?.[0] ?? "";
}
