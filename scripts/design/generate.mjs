import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("design/tokens.json", root), "utf8"));
const css = `/* Generated by npm run design:generate from design/tokens.json. Do not edit. */
@theme static {
${Object.entries(tokens.colors).map(([name, value]) => `  --color-${name}: ${value};`).join("\n")}

  /* Compatibility only. New code uses lot-* / status-* roles. */
${Object.entries(tokens.aliases).map(([name, target]) => `  --color-${name}: var(--color-${target});`).join("\n")}

  --radius-control: 3px;
  --shadow-paper: 12px 16px 0 var(--color-lot-paper-shadow);
  --shadow-paper-sm: 6px 8px 0 var(--color-lot-paper-shadow);
  --shadow-card: 6px 8px 0 var(--color-lot-shadow-soft);
  --shadow-overlay: 12px 16px 0 var(--color-lot-shadow-overlay);
  --shadow-callout: 4px 4px 0 var(--color-lot-shadow-soft);
}
`;
const output = new URL("app/design-theme.css", root);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== css) {
    console.error("Design theme is stale. Run npm run design:generate and review the palette change.");
    process.exitCode = 1;
  } else console.log("Generated design theme is current.");
} else {
  writeFileSync(output, css);
  console.log(`Generated ${fileURLToPath(output)}`);
}
