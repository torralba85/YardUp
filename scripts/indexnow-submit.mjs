// Tells Bing (and the other IndexNow engines) which sitemap URLs changed.
//
// CI snapshots the live sitemaps before a production deploy, then submits only
// the URLs that are new, have a later <lastmod>, or left the sitemap:
//   node scripts/indexnow-submit.mjs --snapshot before.json   (before deploy)
//   node scripts/indexnow-submit.mjs --since before.json      (after deploy)
// Resending unchanged URLs on every deploy does not speed up indexing; Bing
// asks for IndexNow pings only on meaningful changes. By hand,
// `npm run seo:indexnow` with no flags still submits every sitemap URL.
//
// The key is public by design: IndexNow proves site ownership by fetching
// https://lotfoundry.net/<key>.txt, which is served from public/.
// public/3fd466e494e5448b98264c54a291b584.txt is a second key, generated by
// OpenSEO for its own IndexNow submissions; keep both files.
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const HOST = "lotfoundry.net";
const KEY = "65863337483e7700112d4b8d056013fa";
const SITEMAPS = ["/sitemap.xml", "/sitemap-adu.xml"];

/** Map each sitemap <loc> to its <lastmod> ("" when the entry has none). */
export function sitemapEntries(xml) {
  const entries = {};
  for (const [, block] of xml.matchAll(/<url>([\s\S]*?)<\/url>/g)) {
    const loc = block.match(/<loc>\s*([^<\s]+)\s*<\/loc>/)?.[1];
    if (!loc) continue;
    entries[loc] = block.match(/<lastmod>\s*([^<\s]+)\s*<\/lastmod>/)?.[1] ?? "";
  }
  return entries;
}

/**
 * URLs worth a ping after a deploy: added, re-dated, or dropped from the
 * sitemap (so engines recrawl and see the 404, redirect or noindex).
 */
export function changedUrls(before, after) {
  const changed = Object.keys(after).filter((url) => before[url] !== after[url]);
  const removed = Object.keys(before).filter((url) => !(url in after));
  return [...changed, ...removed];
}

async function fetchSitemaps() {
  const entries = {};
  for (const path of SITEMAPS) {
    // Cache-bust: right after a deploy the edge can still hold the old sitemap.
    const response = await fetch(`https://${HOST}${path}?v=${Date.now()}`);
    if (!response.ok) throw new Error(`${path} returned ${response.status}`);
    Object.assign(entries, sitemapEntries(await response.text()));
  }
  return entries;
}

async function readSnapshot(file) {
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch (error) {
    console.warn(`IndexNow: no usable snapshot at ${file} (${error.message}); submitting every sitemap URL.`);
    return null;
  }
}

async function main(args) {
  const flag = args[0];
  const file = args[1];
  if ((flag === "--snapshot" || flag === "--since") && !file) {
    throw new Error(`${flag} needs a file path.`);
  }

  const current = await fetchSitemaps();

  if (flag === "--snapshot") {
    await writeFile(file, JSON.stringify(current, null, 2));
    console.log(`IndexNow: saved ${Object.keys(current).length} sitemap URLs to ${file}`);
    return;
  }

  const before = flag === "--since" ? await readSnapshot(file) : null;
  const urls = before ? changedUrls(before, current) : Object.keys(current);
  if (urls.length === 0) {
    console.log("IndexNow: no sitemap URLs changed; nothing to submit.");
    return;
  }

  const keyCheck = await fetch(`https://${HOST}/${KEY}.txt`);
  if (!keyCheck.ok || (await keyCheck.text()).trim() !== KEY) {
    throw new Error(`Key file https://${HOST}/${KEY}.txt is not live yet; deploy first.`);
  }

  const response = await fetch("https://api.indexnow.org/indexnow", {
    method: "POST",
    headers: { "content-type": "application/json; charset=utf-8" },
    body: JSON.stringify({
      host: HOST,
      key: KEY,
      keyLocation: `https://${HOST}/${KEY}.txt`,
      urlList: urls,
    }),
  });

  // 200 and 202 both mean accepted; 202 means the key is still being validated.
  console.log(`IndexNow: ${response.status} for ${urls.length} URLs`);
  for (const url of urls) console.log(`  ${url}`);
  if (response.status !== 200 && response.status !== 202) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main(process.argv.slice(2));
}
