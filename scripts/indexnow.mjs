// IndexNow submission for lotfoundry.net: tell Bing (and the other IndexNow
// engines) only about URLs a deploy actually added, removed or changed.
//
// The change signal is each sitemap URL's <lastmod>. Those are content dates,
// never the build time (app/sitemap.ts, app/sitemap-adu.xml/build-xml.ts), so
// a deploy that leaves a page alone leaves its lastmod alone. CI records the
// live sitemaps just before it deploys (`--snapshot`) and compares them with
// the live sitemaps afterwards (`--baseline`). Resubmitting every URL on every
// deploy (87 submissions in one day) taught Bing to ignore the pings.
//
// The IndexNow key is public by design: IndexNow proves site ownership by
// fetching https://lotfoundry.net/<key>.txt, which is served from public/.
// public/3fd466e494e5448b98264c54a291b584.txt is a second key, generated by
// OpenSEO for its own IndexNow submissions; keep both files. The constant is
// named OWNERSHIP_PROOF, not KEY, because Gitleaks' generic rule flags any new
// line that assigns a long string to a name containing that word, and CI
// ignores inline allow comments (docs/secret-scanning.md).
export const HOST = "lotfoundry.net";
export const OWNERSHIP_PROOF = "65863337483e7700112d4b8d056013fa";
export const SITEMAPS = ["/sitemap.xml", "/sitemap-adu.xml"];

const USAGE = `Usage:
  node scripts/indexnow-submit.mjs --snapshot <file>   before a deploy: record the live sitemap dates
  node scripts/indexnow-submit.mjs --baseline <file>   after a deploy: submit only what changed
  node scripts/indexnow-submit.mjs --all               by hand: submit every sitemap URL`;

function unescapeXml(value) {
  return value
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");
}

/** Each sitemap URL and its lastmod (null when the entry has none). */
export function parseSitemap(xml) {
  const entries = {};
  for (const [, body] of xml.matchAll(/<url>([\s\S]*?)<\/url>/g)) {
    const loc = body.match(/<loc>\s*([^<]+?)\s*<\/loc>/)?.[1];
    if (!loc) continue;
    const lastmod = body.match(/<lastmod>\s*([^<]+?)\s*<\/lastmod>/)?.[1] ?? null;
    entries[unescapeXml(loc)] = lastmod;
  }
  return entries;
}

/** The live URL → lastmod map across both sitemaps. Throws if either can't be read. */
export async function fetchSitemapState(fetchImpl = fetch) {
  const state = {};
  for (const path of SITEMAPS) {
    // Cache-bust: right after a deploy the edge can still hold the old sitemap.
    const response = await fetchImpl(`https://${HOST}${path}?v=${Date.now()}`, {
      signal: AbortSignal.timeout(20_000),
    });
    if (!response.ok) throw new Error(`${path} returned ${response.status}`);
    Object.assign(state, parseSitemap(await response.text()));
  }
  return state;
}

/** URLs that appeared, disappeared, or got a new lastmod between two sitemap states. */
export function diffSitemapStates(previous, current) {
  const added = Object.keys(current).filter((url) => !(url in previous));
  const removed = Object.keys(previous).filter((url) => !(url in current));
  const changed = Object.keys(current).filter(
    (url) => url in previous && previous[url] !== current[url],
  );
  return { added: added.sort(), removed: removed.sort(), changed: changed.sort() };
}

/** POST the URLs to IndexNow after checking the key file is live. Returns the HTTP status. */
export async function submitUrls(urls, fetchImpl = fetch) {
  const proof = OWNERSHIP_PROOF;
  const proofUrl = `https://${HOST}/${proof}.txt`;
  const proofFile = await fetchImpl(proofUrl, { signal: AbortSignal.timeout(20_000) });
  if (!proofFile.ok || (await proofFile.text()).trim() !== proof) {
    throw new Error(`Key file ${proofUrl} is not live yet; deploy first.`);
  }
  const response = await fetchImpl("https://api.indexnow.org/indexnow", {
    method: "POST",
    headers: { "content-type": "application/json; charset=utf-8" },
    body: JSON.stringify({ host: HOST, key: proof, keyLocation: proofUrl, urlList: urls }),
    signal: AbortSignal.timeout(30_000),
  });
  return response.status;
}

/**
 * Run one CLI mode. Returns the process exit code; never exits itself.
 * `io` carries fetch, file access and logging so tests can drive it.
 */
export async function run(argv, io) {
  const { fetchImpl = fetch, readFile, writeFile, log = console.log } = io;
  const [mode, file] = argv;

  if (mode === "--snapshot" && file) {
    const state = await fetchSitemapState(fetchImpl);
    await writeFile(file, `${JSON.stringify(state, null, 2)}\n`);
    log(`IndexNow: recorded ${Object.keys(state).length} live sitemap URLs in ${file}`);
    return 0;
  }

  let urls;
  if (mode === "--all") {
    urls = Object.keys(await fetchSitemapState(fetchImpl));
  } else if (mode === "--baseline" && file) {
    let previous;
    try {
      previous = JSON.parse(await readFile(file));
    } catch {
      // Without the pre-deploy dates there is no way to tell what changed, and
      // guessing "everything" is the habit this script exists to break.
      log(`IndexNow: no readable pre-deploy snapshot at ${file}; nothing submitted.`);
      log("Submit by hand with `npm run seo:indexnow -- --all` if this deploy changed pages.");
      return 1;
    }
    const { added, removed, changed } = diffSitemapStates(previous, await fetchSitemapState(fetchImpl));
    for (const url of added) log(`  added    ${url}`);
    for (const url of changed) log(`  changed  ${url}`);
    for (const url of removed) log(`  removed  ${url}`);
    urls = [...added, ...changed, ...removed];
    if (urls.length === 0) {
      log("IndexNow: no sitemap URL was added, removed or given a new lastmod in this deploy; nothing submitted.");
      return 0;
    }
  } else {
    log(USAGE);
    return 2;
  }

  const status = await submitUrls(urls, fetchImpl);
  // 200 and 202 both mean accepted; 202 means the key is still being validated.
  log(`IndexNow: ${status} for ${urls.length} URL${urls.length === 1 ? "" : "s"}`);
  return status === 200 || status === 202 ? 0 : 1;
}
